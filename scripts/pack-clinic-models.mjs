// Lossless transport pack for the five accepted clinic GLBs.
//
// The GLB bytes are concatenated in authored order and compressed as ONE
// long-window zstd frame, so textures/skins repeated across files are sent
// once. The browser decodes the frame and slices the exact original GLB
// bytes back out; nothing about the models themselves changes.
//
// usage: node scripts/pack-clinic-models.mjs          (write)
//        node scripts/pack-clinic-models.mjs --check  (verify committed pack)
import fs from 'node:fs'
import crypto from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { ZSTDDecoder } from 'three/addons/libs/zstddec.module.js'

const SRC = 'public/models/3d-redesign/'
const OUT = 'src/three/clinic/pack/'
// Content-addressed public name: immutable bytes per URL, so any cache
// layer can keep it and a new pack never collides with an old one.
const PUBLIC_DIR = 'public/models/pack/'
const ASSETS = ['clinic-shell', 'consultation', 'physician-seated', 'patient-seated', 'room-people']
const sha = b => crypto.createHash('sha256').update(b).digest('hex')

const parts = ASSETS.map(name => ({ name, bytes: fs.readFileSync(`${SRC}${name}.glb`) }))
const joined = Buffer.concat(parts.map(p => p.bytes))
let offset = 0
const files = parts.map(p => { const f = { name: p.name, offset, length: p.bytes.length, sha256: sha(p.bytes) }; offset += p.bytes.length; return f })

async function roundTrip(packed) {
  const decoder = new ZSTDDecoder()
  await decoder.init()
  const out = decoder.decode(new Uint8Array(packed), joined.length)
  for (const f of files) {
    const slice = out.subarray(f.offset, f.offset + f.length)
    if (sha(slice) !== f.sha256) throw new Error(`round trip mismatch: ${f.name}`)
  }
  return out.length
}

if (process.argv.includes('--check')) {
  const manifest = JSON.parse(fs.readFileSync(`${OUT}manifest.json`, 'utf8'))
  if (JSON.stringify(manifest.files) !== JSON.stringify(files)) throw new Error('manifest is stale: re-run pack-clinic-models.mjs')
  const ts = fs.readFileSync(`${OUT}manifest.ts`, 'utf8')
  for (const f of files) if (!ts.includes(`{ name: '${f.name}', offset: ${f.offset}, length: ${f.length} }`)) throw new Error(`manifest.ts is stale: ${f.name}`)
  if (!ts.includes(`PACK_TOTAL = ${joined.length}\n`)) throw new Error('manifest.ts total is stale')
  const packed = fs.readFileSync(`public/${manifest.packFile}`)
  if (sha(packed) !== manifest.packSha256) throw new Error('pack bytes do not match manifest')
  if (!ts.includes(`PACK_URL = '${manifest.packFile}'`)) throw new Error('manifest.ts url is stale')
  const stray = fs.readdirSync(PUBLIC_DIR).filter(f => `models/pack/${f}` !== manifest.packFile)
  if (stray.length) throw new Error(`stale packs in ${PUBLIC_DIR}: ${stray}`)
  await roundTrip(packed)
  console.log(JSON.stringify({ ok: true, files: files.length, raw: joined.length, packed: packed.length }))
} else {
  fs.mkdirSync(OUT, { recursive: true })
  const tmp = `${OUT}.joined.bin`
  fs.writeFileSync(tmp, joined)
  // windowLog 24 (16 MiB) covers the whole 13 MB payload: every cross-file
  // duplicate is reachable. The browser decoder's default limit is 2^27.
  const packed = execFileSync('zstd', ['--ultra', '-22', '--long=24', '-c', tmp], { maxBuffer: 64 << 20 })
  fs.rmSync(tmp)
  await roundTrip(packed)
  const packFile = `models/pack/clinic-models.${sha(packed).slice(0, 16)}.zst`
  fs.rmSync(PUBLIC_DIR, { recursive: true, force: true })
  fs.mkdirSync(PUBLIC_DIR, { recursive: true })
  fs.writeFileSync(`public/${packFile}`, packed)
  fs.writeFileSync(`${OUT}manifest.json`, JSON.stringify({ total: joined.length, packFile, packSha256: sha(packed), files }, null, 2) + '\n')
  const entries = files.map(f => `  { name: '${f.name}', offset: ${f.offset}, length: ${f.length} },`).join('\n')
  fs.writeFileSync(`${OUT}manifest.ts`, `// Generated by scripts/pack-clinic-models.mjs. Do not edit.\nexport const PACK_URL = '${packFile}'\nexport const PACK_TOTAL = ${joined.length}\nexport const PACK_FILES = [\n${entries}\n] as const\n`)
  console.log(JSON.stringify({ raw: joined.length, packed: packed.length, ratio: +(packed.length / joined.length).toFixed(3) }))
}
